#!/usr/bin/env python3
"""Write NOTICE from NOTICE files inside the jars jcsa_dist ships."""

from __future__ import annotations

import argparse
import sys
import zipfile
from pathlib import Path

NOTICE_NAMES = {"notice", "notice.txt", "notice.md"}

HEADER = """\
JCSA-Tools
Copyright 2026 Airbus Defence and Space Oy

This product includes software from the projects listed below. The attribution
notices from their NOTICE files are reproduced unchanged.
Generated by scripts/notice.py.
"""


def notice_texts(jar: Path) -> list[str]:
    texts: list[str] = []
    seen: set[str] = set()
    with zipfile.ZipFile(jar) as zf:
        for name in zf.namelist():
            if Path(name).name.lower() not in NOTICE_NAMES:
                continue
            text = zf.read(name).decode("utf-8", errors="replace").strip()
            if text and text not in seen:
                seen.add(text)
                texts.append(text)
    return texts


def collect(dirs: list[Path]) -> list[tuple[list[str], str]]:
    by_text: dict[str, list[str]] = {}
    for directory in dirs:
        if not directory.is_dir():
            print(f"skip missing directory: {directory}", file=sys.stderr)
            continue
        for jar in sorted(directory.glob("*.jar")):
            for text in notice_texts(jar):
                jars = by_text.setdefault(text, [])
                if jar.name not in jars:
                    jars.append(jar.name)
    groups = [(sorted(jars), text) for text, jars in by_text.items()]
    groups.sort(key=lambda item: item[0])
    return groups


def render(groups: list[tuple[list[str], str]]) -> str:
    parts = [HEADER.rstrip(), ""]
    if not groups:
        parts.append("No third-party NOTICE files were found.")
        parts.append("")
    for jars, text in groups:
        parts.append("-" * 72)
        parts.append(", ".join(jars))
        parts.append("-" * 72)
        parts.append("")
        parts.append(text)
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Write NOTICE from NOTICE files in distributed dependency jars.")
    parser.add_argument("--out", type=Path, required=True, help="NOTICE file to write.")
    parser.add_argument("--dir", type=Path, action="append", required=True)
    args = parser.parse_args()

    groups = collect(args.dir)
    args.out.write_text(render(groups), encoding="utf-8")
    print(f"wrote {args.out} ({len(groups)} notices)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
